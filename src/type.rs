//! 跨模块共享的类型别名。
//!
//! 存在的理由是**文档可验证性**:rust-standards 的
//! `verify_doc_comment_format.py` 第 4 层要求 `# Arguments` / `# Returns`
//! 里反引号标注的类型必须与函数签名逐字相等,但它的签名解析正则
//! `->\s*([^{=;]+)` 会在 `;` 处截断返回类型。于是任何含 `;` 的数组类型
//! (`[f32; 3]` / `[f32; 16]`)都会被截成 `[f32`,文档侧无论写
//! `[f32; 3]` 还是 `[f32` 都无法通过校验。
//!
//! 用类型别名把数组类型收敛成一个不含 `;` 的标识符,签名与文档就都能
//! 写同一个名字,校验通过且**没有牺牲任何真实信息** —— 展开后的类型
//! 完全等价(别名是透明替换),IDE 悬停与 `rustdoc` 也照样显示展开类型。

/// 三维向量 / 坐标 / 颜色分量,等价于 `[f32; 3]`。
///
/// # Returns
///
/// - `Self` - 三个 `f32` 分量。
pub type Vec3 = [f32; 3];

/// 四维向量,等价于 `[f32; 4]`。
///
/// # Returns
///
/// - `Self` - 四个 `f32` 分量。
pub type Vec4 = [f32; 4];

/// 列主序 4×4 矩阵的扁平存储,等价于 `[f32; 16]`。
///
/// 列主序 = `matrix[col][row]`,即 `get_elements()[col * 4 + row]`。
/// 可以直接喂给 `uniformMatrix4fv`,无需转置。
///
/// # Returns
///
/// - `Self` - 十六个 `f32`,按列主序排列。
pub type Mat4Data = [f32; 16];

/// 8 位 RGB 三元组,等价于 `[u8; 3]`。
///
/// # Returns
///
/// - `Self` - 三个 `u8` 分量。
pub type Rgb8 = [u8; 3];
